package com.example.tunnel.payload

import java.nio.charset.StandardCharsets
import java.security.SecureRandom

/**
 * Payload engine providing full functional compatibility with HTTP Tweak / HTTP Injector payloads.
 * Evaluates standard HTTP Tweak tokens, custom HTTP methods, header templates, and Bug Host fronting.
 * Enforces explicit write boundaries via [split] and [delay_split] without conflating ordinary HTTP
 * header terminators ([crlf][crlf]) with packet boundaries.
 */
object PayloadBuilder {

    const val DEFAULT_CONNECT_PAYLOAD =
        "CONNECT [host_port] HTTP/1.1[crlf]Host: [host][crlf]X-Forwarded-For: [host][crlf]User-Agent: [ua][crlf]Connection: Upgrade[crlf][crlf]"

    const val WEBSOCKET_PAYLOAD =
        "GET /tunnel HTTP/1.1[crlf]Host: [host][crlf]Upgrade: websocket[crlf]Connection: Upgrade[crlf]Sec-WebSocket-Key: [raw][crlf]Sec-WebSocket-Version: 13[crlf][crlf]"

    const val DIRECT_FRONTING_PAYLOAD =
        "POST / HTTP/1.1[crlf]Host: [host][crlf]X-Online-Host: [host][crlf]User-Agent: [ua][crlf]Connection: Keep-Alive[crlf][crlf]"

    const val SPLIT_PAYLOAD =
        "CONNECT [host_port] [protocol][crlf]Host: [host][crlf][split]GET / [protocol][crlf]Host: [host][crlf][crlf]"

    const val DEFAULT_USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"
    const val DEFAULT_PROTOCOL = "HTTP/1.1"

    /**
     * Exact set of 17 supported HTTP Tweak tokens. No additional tokens are permitted.
     */
    val SUPPORTED_TOKENS: Set<String> = setOf(
        "[host]",
        "[port]",
        "[host_port]",
        "[target_host]",
        "[target_port]",
        "[target_host_port]",
        "[protocol]",
        "[ua]",
        "[raw]",
        "[real_raw]",
        "[netData]",
        "[auth]",
        "[crlf]",
        "[cr]",
        "[lf]",
        "[split]",
        "[delay_split]"
    )

    private val secureRandom = SecureRandom()

    enum class SplitMarker {
        NONE,
        INSTANT,      // Generated by [split]
        DELAYED       // Generated by [delay_split]
    }

    data class PayloadSegment(
        val data: ByteArray,
        val splitMarker: SplitMarker = SplitMarker.NONE
    ) {
        val text: String get() = String(data, StandardCharsets.UTF_8)
        val size: Int get() = data.size

        override fun equals(other: Any?): Boolean {
            if (this === other) return true
            if (javaClass != other?.javaClass) return false
            other as PayloadSegment
            if (!data.contentEquals(other.data)) return false
            if (splitMarker != other.splitMarker) return false
            return true
        }

        override fun hashCode(): Int {
            var result = data.contentHashCode()
            result = 31 * result + splitMarker.hashCode()
            return result
        }
    }

    data class ValidationResult(
        val isValid: Boolean,
        val issues: List<String> = emptyList()
    ) {
        fun throwIfInvalid() {
            if (!isValid) {
                throw IllegalArgumentException("Payload validation failed: ${issues.joinToString("; ")}")
            }
        }
    }

    /**
     * Validates that payload template contains only balanced, well-formed, supported HTTP Tweak tokens.
     * Reports unclosed tokens, malformed brackets, and unsupported tokens without modifying the payload.
     */
    fun validatePayload(payload: String): ValidationResult {
        val issues = mutableListOf<String>()
        if (payload.isBlank()) {
            issues.add("Payload cannot be empty")
            return ValidationResult(false, issues)
        }

        var i = 0
        val len = payload.length

        while (i < len) {
            val char = payload[i]
            if (char == '[') {
                val closingIdx = payload.indexOf(']', i + 1)
                if (closingIdx == -1) {
                    issues.add("Unclosed token starting at index $i: '${payload.substring(i)}'")
                    break
                }
                val nextOpen = payload.indexOf('[', i + 1)
                if (nextOpen in (i + 1) until closingIdx) {
                    issues.add("Malformed token: unexpected '[' before closing ']' at index $nextOpen")
                    i = nextOpen
                    continue
                }
                val token = payload.substring(i, closingIdx + 1)
                if (token == "[]") {
                    issues.add("Malformed empty token '[]' at index $i")
                } else if (token !in SUPPORTED_TOKENS) {
                    issues.add("Unsupported token '$token' at index $i")
                }
                i = closingIdx + 1
            } else if (char == ']') {
                issues.add("Unexpected closing bracket ']' at index $i")
                i++
            } else {
                i++
            }
        }

        return ValidationResult(issues.isEmpty(), issues)
    }

    /**
     * Validates target host and port before evaluation.
     */
    fun validateTarget(targetHost: String, targetPort: Int): ValidationResult {
        val issues = mutableListOf<String>()
        val trimmed = targetHost.trim()
        if (trimmed.isEmpty()) {
            issues.add("Target host cannot be empty")
        }
        if (trimmed.contains('\r') || trimmed.contains('\n')) {
            issues.add("Target host contains illegal CRLF characters")
        }
        if (trimmed.any { it.isWhitespace() }) {
            issues.add("Target host cannot contain whitespace")
        }
        if (targetPort !in 1..65535) {
            issues.add("Target port must be between 1 and 65535 (was: $targetPort)")
        }
        return ValidationResult(issues.isEmpty(), issues)
    }

    private fun sanitizeConfigValue(name: String, value: String?): String? {
        if (value == null) return null
        if (value.contains('\r') || value.contains('\n')) {
            throw IllegalArgumentException("$name contains illegal CRLF characters")
        }
        return value
    }

    private data class RawChunk(val text: String, val marker: SplitMarker)

    private fun splitTemplate(template: String): List<RawChunk> {
        val chunks = mutableListOf<RawChunk>()
        var currentIndex = 0
        while (currentIndex < template.length) {
            val splitIdx = template.indexOf("[split]", currentIndex)
            val delayIdx = template.indexOf("[delay_split]", currentIndex)

            if (splitIdx == -1 && delayIdx == -1) {
                chunks.add(RawChunk(template.substring(currentIndex), SplitMarker.NONE))
                break
            }

            val nextMarkerIndex: Int
            val markerType: SplitMarker
            val markerLen: Int

            if (splitIdx != -1 && (delayIdx == -1 || splitIdx < delayIdx)) {
                nextMarkerIndex = splitIdx
                markerType = SplitMarker.INSTANT
                markerLen = "[split]".length
            } else {
                nextMarkerIndex = delayIdx
                markerType = SplitMarker.DELAYED
                markerLen = "[delay_split]".length
            }

            chunks.add(RawChunk(template.substring(currentIndex, nextMarkerIndex), markerType))
            currentIndex = nextMarkerIndex + markerLen
        }
        return chunks.ifEmpty { listOf(RawChunk(template, SplitMarker.NONE)) }
    }

    /**
     * Evaluates a payload template into structured segments.
     * Preserves explicit write boundaries from [split] and [delay_split] markers.
     * Ordinary [crlf][crlf] headers are preserved without splitting.
     */
    fun buildSegments(
        template: String,
        targetHost: String,
        targetPort: Int,
        bugHost: String? = null,
        userAgent: String = DEFAULT_USER_AGENT,
        protocol: String = DEFAULT_PROTOCOL,
        proxyUsername: String? = null,
        proxyPassword: String? = null
    ): List<PayloadSegment> {
        validatePayload(template).throwIfInvalid()
        validateTarget(targetHost, targetPort).throwIfInvalid()

        val sanitizedTargetHost = targetHost.trim()
        val sanitizedBugHost = sanitizeConfigValue("Bug host", bugHost?.trim())
        val sanitizedUa = sanitizeConfigValue("User-Agent", userAgent) ?: DEFAULT_USER_AGENT
        val sanitizedProto = sanitizeConfigValue("Protocol", protocol) ?: DEFAULT_PROTOCOL
        val sanitizedUser = sanitizeConfigValue("Proxy username", proxyUsername)
        val sanitizedPass = sanitizeConfigValue("Proxy password", proxyPassword)

        if (sanitizedBugHost != null && sanitizedBugHost.any { it.isWhitespace() }) {
            throw IllegalArgumentException("Bug host cannot contain whitespace")
        }

        val effectiveHost = if (!sanitizedBugHost.isNullOrBlank()) sanitizedBugHost else sanitizedTargetHost
        val effectivePort = targetPort.toString()
        val effectiveHostPort = "$effectiveHost:$effectivePort"
        val targetHostPort = "$sanitizedTargetHost:$targetPort"

        val authHeader = if (!sanitizedUser.isNullOrEmpty()) {
            val creds = "$sanitizedUser:${sanitizedPass ?: ""}"
            "Basic " + encodeBase64(creds.toByteArray(StandardCharsets.UTF_8))
        } else {
            ""
        }

        // Generate nonce only if random tokens are present (ensures deterministic output otherwise)
        val rawNonce = if (template.contains("[raw]") || template.contains("[real_raw]")) {
            val nonceBytes = ByteArray(16)
            secureRandom.nextBytes(nonceBytes)
            encodeBase64(nonceBytes)
        } else {
            ""
        }

        val chunks = splitTemplate(template)

        return chunks.map { chunk ->
            val evaluated = evaluateTokens(
                text = chunk.text,
                targetHost = sanitizedTargetHost,
                targetPort = targetPort.toString(),
                targetHostPort = targetHostPort,
                effectiveHost = effectiveHost,
                effectivePort = effectivePort,
                effectiveHostPort = effectiveHostPort,
                protocol = sanitizedProto,
                userAgent = sanitizedUa,
                authHeader = authHeader,
                rawNonce = rawNonce
            )
            PayloadSegment(
                data = evaluated.toByteArray(StandardCharsets.UTF_8),
                splitMarker = chunk.marker
            )
        }
    }

    /**
     * Builds and evaluates the complete HTTP payload string, substituting all variables.
     */
    fun buildPayload(
        template: String,
        targetHost: String,
        targetPort: Int,
        bugHost: String? = null,
        userAgent: String = DEFAULT_USER_AGENT,
        protocol: String = DEFAULT_PROTOCOL,
        proxyUsername: String? = null,
        proxyPassword: String? = null
    ): String {
        val segments = buildSegments(
            template = template,
            targetHost = targetHost,
            targetPort = targetPort,
            bugHost = bugHost,
            userAgent = userAgent,
            protocol = protocol,
            proxyUsername = proxyUsername,
            proxyPassword = proxyPassword
        )
        return segments.joinToString("") { it.text }
    }

    private fun evaluateTokens(
        text: String,
        targetHost: String,
        targetPort: String,
        targetHostPort: String,
        effectiveHost: String,
        effectivePort: String,
        effectiveHostPort: String,
        protocol: String,
        userAgent: String,
        authHeader: String,
        rawNonce: String
    ): String {
        // Replace longer compound tokens before shorter tokens to prevent sub-string collision
        return text
            .replace("[target_host_port]", targetHostPort)
            .replace("[target_host]", targetHost)
            .replace("[target_port]", targetPort)
            .replace("[host_port]", effectiveHostPort)
            .replace("[host]", effectiveHost)
            .replace("[port]", effectivePort)
            .replace("[netData]", "CONNECT $targetHostPort $protocol")
            .replace("[protocol]", protocol)
            .replace("[ua]", userAgent)
            .replace("[auth]", authHeader)
            .replace("[raw]", rawNonce)
            .replace("[real_raw]", rawNonce)
            .replace("[crlf]", "\r\n")
            .replace("[cr]", "\r")
            .replace("[lf]", "\n")
    }

    /**
     * Splits payload into segments.
     * Uses explicit [split] and [delay_split] boundary markers if present.
     * Ordinary HTTP header terminators (\r\n\r\n) do NOT create split boundaries.
     */
    fun getPayloadSegments(
        template: String,
        targetHost: String,
        targetPort: Int,
        bugHost: String? = null,
        userAgent: String = DEFAULT_USER_AGENT,
        protocol: String = DEFAULT_PROTOCOL,
        proxyUsername: String? = null,
        proxyPassword: String? = null
    ): List<ByteArray> {
        return buildSegments(
            template = template,
            targetHost = targetHost,
            targetPort = targetPort,
            bugHost = bugHost,
            userAgent = userAgent,
            protocol = protocol,
            proxyUsername = proxyUsername,
            proxyPassword = proxyPassword
        ).map { it.data }
    }

    /**
     * Overload for backward compatibility. If [split] or [delay_split] markers are present,
     * splits on those markers. Does NOT split on ordinary \r\n\r\n header terminators.
     */
    fun getPayloadSegments(payload: String): List<ByteArray> {
        if (payload.contains("[split]") || payload.contains("[delay_split]")) {
            val chunks = splitTemplate(payload)
            return chunks.map { it.text.toByteArray(StandardCharsets.UTF_8) }
        }
        return listOf(payload.toByteArray(StandardCharsets.UTF_8))
    }

    private fun encodeBase64(bytes: ByteArray): String {
        return try {
            java.util.Base64.getEncoder().encodeToString(bytes)
        } catch (_: Throwable) {
            android.util.Base64.encodeToString(bytes, android.util.Base64.NO_WRAP)
        }
    }
}
